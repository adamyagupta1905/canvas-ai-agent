"""Course dashboard: an all-courses page plus, for every course, the same tabs:

    Overview · Grades · Notes · Plan · Deadlines · Sources

    .venv/bin/streamlit run app.py          (bookmark a course with ?course=CODE)

Reads local data only (data/, gitignored). Every number and every view is built by Python
(canvas_agent.grades / component_check / course_view); nothing on this page is generated by an LLM.
Demo mode (no data/) shows a synthetic course.
"""

from __future__ import annotations

import json
import os
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path

import altair as alt
import pandas as pd
import streamlit as st

from canvas_agent import course_view as cv
from canvas_agent.grades import grade_summary, tracker
from canvas_agent.tools import Store

ROOT = Path(__file__).parent
DATA = Path(os.environ.get("COURSE_DATA_DIR") or ROOT / "data")
DEMO = False
if not (DATA / "canvas_snapshot.json").exists() and (ROOT / "demo_data" / "canvas_snapshot.json").exists():
    DATA, DEMO = ROOT / "demo_data", True  # no real data: run on the committed fictional demo
DEMO = DEMO or (DATA / "demo_meta.json").exists()  # the fictional demo, however it was selected
os.environ["COURSE_DATA_DIR"] = str(DATA)  # so helper scripts (recheck) read the same folder
SYL = DATA / "syllabi"
REAL = (DATA / "canvas_snapshot.json").exists()

st.set_page_config(page_title="Course dashboard", layout="wide")
_meta = DATA / "demo_meta.json"
now = (datetime.fromisoformat(json.loads(_meta.read_text())["as_of"]) if _meta.exists()  # demo: frozen "today"
       else datetime.now(timezone.utc))


def pct(x) -> str:
    return "n/a" if x is None else f"{x:.2f}%"


def demo_courses() -> dict:
    from canvas_agent.sources import FixtureSource

    src = FixtureSource(ROOT / "tests" / "fixtures" / "courses")
    items = [[a.name, a.due_at.isoformat() if a.due_at else None, a.points_possible, a.state.value, a.score, False]
             for a in src.list_assignments("ECON101")]
    return {"ECON101": {"name": "Demo course (synthetic)", "weighted": False,
                        "groups": [{"name": "Assignments", "weight": 0, "rules": {}, "items": items}]}}


