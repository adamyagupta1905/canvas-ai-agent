def all_courses_page() -> None:
    st.title("All courses")
    if not REAL:
        st.info("Connect a course to see the overview.")
        return
    rows = cv.overview(store, now)
    st.dataframe(pd.DataFrame([{
        "Course": f"{r['code']}: {r['name']}", "Grade now": r["grade_pct"], "Graded so far %": r["graded_weight_pct"],
        "Course progress %": r["course_progress_pct"], "Next deadline": r["next_deadline"] or "-", "Grade basis": r["basis"],
    } for r in rows]), hide_index=True, use_container_width=True, column_config={
        "Grade now": st.column_config.NumberColumn(format="%.2f%%"),
        "Course progress %": st.column_config.ProgressColumn(min_value=0, max_value=100, format="%.0f%%"),
        "Graded so far %": st.column_config.ProgressColumn(min_value=0, max_value=100, format="%.0f%%")})

    st.subheader("Next 14 days, all courses")
    upcoming = []
    for code in courses:
        for d in cv.deadlines(store, code, now):
            if d["when"] <= now + timedelta(days=14) and d["status"] not in ("awaiting_grade", "not_yet_available"):
                upcoming.append({"When": d["when"].strftime("%a %b %d %H:%M") if d["has_time"] else d["when"].strftime("%a %b %d"),
                                 "_sort": d["when"], "Course": code, "What": d["what"], "% of grade": d["pct_of_grade"],
                                 "From": ", ".join(d["sources"]), "Status": d["status"].replace("_", " ")})
    if upcoming:
        df = pd.DataFrame(sorted(upcoming, key=lambda r: r["_sort"])).drop(columns="_sort")
        st.dataframe(df, hide_index=True, use_container_width=True)
    else:
        st.caption("Nothing due in the next 14 days.")

    asks = [r for f in SYL.glob("*.facts.json") for r in json.loads(f.read_text()).get("input_requests", [])]
    if asks:
        st.subheader("Waiting for your input")
        for r in asks:
            st.markdown(f"- **{r['course']} · {r['component']} ({r['weight_pct']:g}%)**: {r['reason']}")


