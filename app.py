def overview_tab(code: str, course: dict, facts: dict | None) -> None:
    p = cv.progress(store, code, now) if REAL else None
    canvas_view = grade_summary(code, course)
    syl = (facts or {}).get("syllabus_view_grade")
    c1, c2, c3, c4 = st.columns(4)
    if syl:
        c1.metric("Current grade (syllabus rules)", pct(syl["current_pct"]),
                  help="Syllabus weights and rules applied to all marks we have, including ones you entered.")
        c3.metric("Possible finish", f"{syl['floor_pct']:.0f}–{syl['ceiling_pct']:.0f}%",
                  help="Worst case: everything remaining scores 0. Best case: everything remaining scores 100%.")
        c4.metric("Graded so far", pct(syl["weight_determined"]))
    else:
        c1.metric("Current grade (Canvas weights)", pct(canvas_view.current_pct))
        c3.metric("Possible finish", f"{pct(canvas_view.floor_pct)} – {pct(canvas_view.ceiling_pct)}")
        c4.metric("Graded so far", pct(canvas_view.weight_determined))
    if p:
        c2.metric("Course progress", pct(p["course_progress_pct"]) if p["course_progress_pct"] is not None else "unknown",
                  help=("weeks passed on the course schedule" if p.get("weeks") else
                        "classes held (Canvas Modules)" if p.get("sessions") else "share of dated items already due"))
        if p.get("weeks"):
            st.caption(f"Week {p['weeks']['passed']} of {p['weeks']['total']} (course schedule)")
        elif p.get("sessions") and p["sessions"]["held"]:
            st.caption(f"Class {p['sessions']['held']} of {p['sessions']['total']} (Canvas Modules)")
    if (facts or {}).get("needed"):
        st.caption("Average needed on everything still to be graded: " + " · ".join(
            f"{t}% → **{v:.1f}%**" + (" (out of reach)" if v > 100 else "") for t, v in facts["needed"].items() if v is not None))
    if not syl and course.get("canvas_totals_canvas_only"):
        st.caption(f"Canvas's own total ({course['canvas_totals_canvas_only']['current']}%) covers Canvas data only; "
                   "this grade also includes PrairieLearn scores.")

    warnings = list((facts or {}).get("past_exams_without_score", []))
    warnings += [w for w in canvas_view.warnings if not (syl and "syllabus weights are needed" in w)]
    for w in warnings:
        st.warning(w)
    for pr in (facts or {}).get("pass_requirements", []):
        comps = " + ".join(pr["components"])
        if pr["status"] == "met":
            msg = f"Pass requirement met: {comps} at {pr['current_pct']:.1f}% (need {pr['threshold_pct']:g}%)."
        elif pr["status"] == "safe":
            msg = f"Pass requirement already secured: {comps} at {pr['current_pct']:.1f}% so far (need {pr['threshold_pct']:g}%)."
        elif pr["status"] in ("on_track", "at_risk") and pr["needed_on_remaining_pct"] is not None:
            msg = (f"Pass requirement: {comps} must average at least {pr['threshold_pct']:g}%. You are at "
                   f"{pr['current_pct']:.1f}% on the graded part; you need {pr['needed_on_remaining_pct']:.1f}% on the rest.")
        elif pr["status"] in ("on_track", "at_risk"):
            msg = (f"Pass requirement: {comps} must average at least {pr['threshold_pct']:g}%. "
                   f"You are at {pr['current_pct']:.1f}% so far, with more work still to be graded.")
        else:
            msg = f"Pass requirement: {comps} must average at least {pr['threshold_pct']:g}% (nothing graded yet)."
        (st.error if pr["status"] == "at_risk" else st.success if pr["status"] in ("met", "safe") else st.info)(msg)
    att = (facts or {}).get("attendance_check")
    if att:
        limits = " · ".join(f"more than {t}% = more than {k} of {att['sessions_total']} classes"
                            for t, k in att.get("allowed_absences", {}).items())
        head = "Attendance (confirmed)" if att.get("status") == "confirmed" else "Attendance (possible, unverified)"
        body = (f"**{head}: {len(att['possible_absences'])} absences out of {att['sessions_total']} classes "
                f"({att['possible_absence_pct']}%).**  \nSyllabus limits: {limits}.")
        if att.get("sessions_remaining") is not None:
            body += f"  \nClasses still to come: {att['sessions_remaining']}."
        (st.error if att.get("exceeds") else st.info)(body + f"  \n_{att['caveat']}_")
    if REAL and facts:
        input_section(code, facts)


def input_section(code: str, facts: dict) -> None:
    from canvas_agent.user_inputs import InputStore, UserEntry, split_areas

    istore = InputStore(DATA / "user_inputs.json")
    mine = istore.for_course(code)
    reqs = facts.get("input_requests", [])
    if reqs:
        st.subheader("Needs your input")
    for r in reqs:
        with st.form(f"in-{code}-{r['component']}"):
            st.markdown(f"**{r['component']} ({r['weight_pct']:g}%)**: {r['reason']}"
                        + (f" Likely in **{r['likely_source']}**." if r.get("likely_source") else ""))
            c1, c2, c3 = st.columns([1, 1, 2])
            score = c1.number_input("Your score", min_value=0.0, value=None, step=0.5, key=f"s-{code}-{r['component']}")
            out_of = c2.number_input("Out of", min_value=0.0, value=None, step=0.5, key=f"o-{code}-{r['component']}")
            source = c3.text_input("Where you saw it", value=r.get("likely_source") or "", key=f"src-{code}-{r['component']}")
            improve = st.text_area("Scope for improvement: what did you lose marks on? (separate with ; or new lines)",
                                   key=f"imp-{code}-{r['component']}")
            if st.form_submit_button("Save", disabled=DEMO):
                if (score is None) != (out_of is None) or (out_of is not None and out_of <= 0):
                    st.error("Enter both a score and a positive 'out of', or leave both empty to save feedback only.")
                else:
                    try:
                        istore.add(UserEntry(course=code, component=r["component"], item=r["component"], score=score,
                                             out_of=out_of, source=source or None, improvement_areas=split_areas(improve)))
                        from scripts.syllabus_flow import recheck  # free: recompute with your entry

                        recheck(code, SYL / f"{code}.pdf")
                        st.rerun()
                    except ValueError as e:
                        st.error(str(e))
    if mine:
        st.caption("What you've told me (used in the grade and the plan):")
        st.dataframe(pd.DataFrame([{"Component": e.component, "Score": f"{e.score:g}/{e.out_of:g}" if e.score is not None else "-",
                                    "Source": e.source or "-", "Improve": "; ".join(e.improvement_areas)} for e in mine]),
                     hide_index=True, use_container_width=True)


def component_chart(c: dict) -> None:
    rows = []
    for i in c["items"]:
        status = ("dropped" if i["dropped_syllabus"] else "counted") if i["score"] is not None else "not graded yet"
        label = "not graded" if i["pct"] is None else f"{i['pct']:.0f}%" + (" (dropped)" if status == "dropped" else "")
        rows.append({"Item": i["name"], "Score %": i["pct"] or 0, "Status": status, "Label": label})
    if c.get("sessions_total"):  # one bar per class, including classes with no item and future classes
        present = {int(m.group(1)) for r in rows if (m := re.search(r"class\D{0,3}(\d{1,2})", r["Item"], re.I))}
        rows += [{"Item": f"Class {n:02d} (no exercise)", "Score %": 0, "Status": "no item for this class", "Label": "none"}
                 for n in range(1, c["sessions_total"] + 1) if n not in present]
        rows.sort(key=lambda r: int(m.group(1)) if (m := re.search(r"class\D{0,3}(\d{1,2})", r["Item"], re.I)) else 99)
    if not rows:
        return
    df = pd.DataFrame(rows)
    def short(n: str) -> str:
        if (m := re.search(r"class\D{0,3}(\d{1,2})", n, re.I)):
            return f"C{int(m.group(1)):02d}"
        tail = n.split(": ", 1)[1] if ": " in n else n  # 'Lab Assignments: LAB01 Onboarding' -> 'LAB01 Onboarding'
        return tail.split()[0][:18] if tail.split() else n[:18]

    labels, seen = [], {}
    for n in df["Item"]:  # labels must be unique or Altair merges the bars
        s = short(n)
        seen[s] = seen.get(s, 0) + 1
        labels.append(s if seen[s] == 1 else f"{s} ({seen[s]})")
    df["Short"] = labels
    bars = alt.Chart(df).mark_bar().encode(
        x=alt.X("Short:N", sort=None, title=None, axis=alt.Axis(labelAngle=-45, labelLimit=160)),
        y=alt.Y("Score %:Q", scale=alt.Scale(domain=[0, 100])),
        color=alt.Color("Status:N", scale=alt.Scale(domain=["counted", "dropped", "not graded yet", "no item for this class"],
                                                    range=["#2f6fdf", "#b8b8b8", "#f0c36d", "#e6e6e6"])),
        tooltip=["Item", "Score %", "Status"])
    text = alt.Chart(df).mark_text(angle=270, align="left", dx=4, fontSize=10).encode(
        x=alt.X("Short:N", sort=None), y="Score %:Q", text="Label:N")
    st.altair_chart((bars + text).properties(height=260), use_container_width=True)


def grades_tab(code: str, course: dict, facts: dict | None) -> None:
    checks = (facts or {}).get("component_checks")
    if checks:
        st.dataframe(pd.DataFrame([{
            "Component": c["component"], "Weight %": c["syllabus_weight"],
            "Graded / expected": f"{c['scored']} / {c['expected_items'] if c['expected_items'] is not None else c['items_in_canvas']}",
            "Drop lowest": c["drop_syllabus"] if c["drop_syllabus"] is not None else "-",
            "Average now": c["avg_syllabus_rules"],
            "Adds to grade": round(c["syllabus_weight"] * c["avg_syllabus_rules"] / 100, 2) if c["avg_syllabus_rules"] is not None else None,
        } for c in checks]), hide_index=True, use_container_width=True)
        for c in checks:
            with st.expander(f"{c['component']} ({c['syllabus_weight']:g}%) · average {pct(c['avg_syllabus_rules'])}"):
                for f in c["flags"]:
                    if not f.startswith("Expected item count"):
                        st.markdown(f"- ⚠️ {f}")
                if c.get("expected_source"):
                    st.caption(f"Expected count: {c['expected_items']} ({c['expected_source']})")
                component_chart(c)
                for r in c["rules"]:
                    st.markdown(f"- {r}")
        pending = [m for m in facts.get("item_mapping", []) if m["confidence"] in ("low", "ambiguous", "unmapped")]
        if pending:
            st.caption("Not counted until you confirm them in data/item_overrides.json:")
            st.dataframe(pd.DataFrame([{"Item": m["item"], "Best guess": m["component"] or "-", "Confidence": m["confidence"]}
                                       for m in pending]), hide_index=True)
    else:
        s = grade_summary(code, course)
        st.dataframe(pd.DataFrame([{"Component": g.name, "Weight %": g.weight, "Counted": g.kept, "Average": g.pct,
                                    "Dropped": ", ".join(g.dropped)} for g in s.groups]), hide_index=True, use_container_width=True)
        st.caption("No syllabus rules for this course yet (run the syllabus flow): Canvas's setup is used.")
    st.subheader("Every item")
    rows = tracker(code, course, now)
    st.dataframe(pd.DataFrame([{"Item": r.name, "Component": r.group, "Due": r.due.strftime("%b %d") if r.due else "",
                                "Status": r.status.replace("_", " "), "Score %": r.pct, "% of grade": r.weight_of_final,
                                "Size": r.size} for r in rows]), hide_index=True, use_container_width=True, height=320)


def notes_tab(code: str) -> None:
    secs = cv.notes(store, code, now) if REAL else []
    if not secs:
        st.caption("No course content available yet (crawl the course website or connect Canvas modules).")
        return
    src = "lecture slides on the course website" if secs[0]["kind"] == "lecture slides" else "Canvas modules"
    st.caption(f"{len(secs)} sections from {src}, in course order, up to what has been released. "
               "Extracted outlines (titles, learning goals, slide titles), not generated text.")
    for s in secs:
        label = (f"Week {s['week']} · " if s["week"] else "") + s["title"]
        with st.expander(label):
            if s["goals"]:
                st.markdown("**Learning goals**")
                for g in s["goals"]:
                    st.markdown(f"- {g}")
            if s["points"]:
                st.markdown("**Covered**")
                st.markdown("\n".join(f"- {p}" for p in s["points"][:25]))
            if s["scores"]:
                st.markdown("**How you did**: " + ", ".join(f"{x['item']} {x['pct']:.0f}%" for x in s["scores"]))
            if s["source"].startswith("http"):
                st.markdown(f"[Open source]({s['source']})")


def plan_tab(code: str) -> None:
    if not REAL:
        return
    p = cv.plan(store, code, now)
    st.caption(f"From {p['from']} to {p['to']}. Rules: a work block the day before each deadline; review 7, 4, 2 and 1 "
               "days before each exam, rotating through your weak areas first, then the course units.")
    st.markdown("**Weak areas used for review:** " + "; ".join(p["weak_areas"]))
    if not p["days"]:
        st.caption("Nothing to plan in this window.")
    for d in p["days"]:
        day = datetime.fromisoformat(d["date"])
        st.markdown(f"**{day:%a %b %d}**")
        for t in d["tasks"]:
            st.markdown(f"- {t['task']}  \n  <span style='opacity:0.6'>{t['why']}</span>", unsafe_allow_html=True)


def deadlines_tab(code: str) -> None:
    if not REAL:
        return
    ds = cv.deadlines(store, code, now)
    if not ds:
        st.caption("No upcoming deadlines found.")
        return
    st.dataframe(pd.DataFrame([{
        "When": d["when"].strftime("%a %b %d %H:%M") if d["has_time"] else d["when"].strftime("%a %b %d"),
        "Days left": d["days_left"], "What": d["what"], "% of grade": d["pct_of_grade"],
        "Status": d["status"].replace("_", " "), "From": ", ".join(d["sources"])} for d in ds]),
        hide_index=True, use_container_width=True,
        column_config={"Days left": st.column_config.NumberColumn(format="%.1f")})
    st.caption("Merged from Canvas, PrairieLearn, the course website schedule and the syllabus. Times are local.")


def sources_tab(code: str, facts: dict | None) -> None:
    from canvas_agent.prairielearn import summarise

    pl = [x for x in store.pl() if x.course == code] if REAL else []
    if pl:
        st.subheader("PrairieLearn")
        notes = store.merge_notes(code)
        if notes:
            st.dataframe(pd.DataFrame([{"Action": n.action, "Canvas": n.canvas_item or f"[{n.canvas_group}]",
                                        "PrairieLearn": n.pl_assessment, "Detail": n.detail} for n in notes]),
                         hide_index=True, use_container_width=True)
        summ = summarise(store.pl(), code, now)
        if summ["awaiting_grade"]:
            st.caption("Submitted, waiting for manual grading (not a zero): "
                       + ", ".join(f"{x['label']} ({x['pending_points']:g} pts)" for x in summ["awaiting_grade"]))
        st.dataframe(pd.DataFrame([{"Label": x.label, "Title": x.title, "Kind": x.kind, "Status": x.status.replace("_", " "),
                                    "Points": f"{x.earned:g}/{x.possible:g}" if x.possible else "", "Score %": x.pct}
                                   for x in pl]), hide_index=True, use_container_width=True, height=260)
    site_dir = DATA / "sites" / code
    if REAL and (site_dir / "manifest.json").exists():
        from canvas_agent.website import load_manifest, search

        man = load_manifest(site_dir)
        st.subheader("Course website")
        st.caption(f"{man.start_urls[0]} · {len(man.docs)} documents · crawled {man.crawled_at[:16].replace('T', ' ')} UTC")
        q = st.text_input("Search slides, textbook and project specs", key=f"search-{code}")
        if q:
            for h in search(site_dir, q, k=5):
                st.markdown(f"**{h['title']}** · {h['kind']} · page {h['page']} · [open]({h['url']})")
                st.caption(re.sub(r"(?m)^#+\s*", "", h["snippet"]).replace("\n", " ")[:300] + "…")
    if facts:
        st.subheader("Syllabus")
        st.caption(f"Source: {facts.get('source', '')}")
        for h in facts.get("exam_date_hints", []):
            st.info(f"Possible {h['kind']} date found in {h['source']}: **{h['found_date']}**  \n_\"{h['quote']}\"_")


def course_page(code: str) -> None:
    course = courses[code]
    facts_path = SYL / f"{code}.facts.json"
    facts = json.loads(facts_path.read_text()) if facts_path.exists() else None
    st.title(f"{code}: {course['name']}")
    tabs = st.tabs(["Overview", "Grades", "Notes", "Plan", "Deadlines", "Sources"])
    with tabs[0]:
        overview_tab(code, course, facts)
    with tabs[1]:
        grades_tab(code, course, facts)
    with tabs[2]:
        notes_tab(code)
    with tabs[3]:
        plan_tab(code)
    with tabs[4]:
        deadlines_tab(code)
    with tabs[5]:
        sources_tab(code, facts)


if page == "All courses":
    all_courses_page()
else:
    course_page(page)
